-- Encontros de devolução combinados no chat entre quem está com o animal
-- (autor da publicação de "encontrado") e o tutor que comprovou a posse.
--
-- Cada proposta é uma linha. Uma contraproposta ou remarcação marca a linha
-- anterior como 'superseded' e cria uma nova (parent_id aponta para a anterior),
-- então o histórico de idas e vindas fica preservado.
--
-- Status: proposed -> confirmed | declined | superseded | cancelled
--         confirmed -> cancelled | superseded
--
-- Privacidade: o ponto é escolhido no mapa como local público de encontro e o
-- endereço é salvo sem número de casa (o app já remove antes de gravar).

CREATE TABLE IF NOT EXISTS public.return_meetups (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id integer NOT NULL REFERENCES public.items(id) ON DELETE CASCADE,
  finder_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  claimant_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  proposed_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  parent_id bigint REFERENCES public.return_meetups(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'proposed'
    CHECK (status IN ('proposed', 'confirmed', 'declined', 'superseded', 'cancelled')),
  meeting_at timestamptz NOT NULL,
  latitude double precision NOT NULL,
  longitude double precision NOT NULL,
  address_text text NOT NULL DEFAULT '',
  note text,
  response_note text,
  responded_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  responded_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (finder_id <> claimant_id),
  CHECK (proposed_by IN (finder_id, claimant_id))
);

CREATE INDEX IF NOT EXISTS return_meetups_pair_idx
  ON public.return_meetups (item_id, finder_id, claimant_id, created_at DESC);

-- Mantém updated_at atualizado
CREATE OR REPLACE FUNCTION public.return_meetups_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS return_meetups_touch_updated_at ON public.return_meetups;
CREATE TRIGGER return_meetups_touch_updated_at
  BEFORE UPDATE ON public.return_meetups
  FOR EACH ROW EXECUTE FUNCTION public.return_meetups_touch_updated_at();

ALTER TABLE public.return_meetups ENABLE ROW LEVEL SECURITY;

-- Só os dois participantes enxergam o encontro
DROP POLICY IF EXISTS "return_meetups_select_participants" ON public.return_meetups;
CREATE POLICY "return_meetups_select_participants"
  ON public.return_meetups FOR SELECT
  TO authenticated
  USING (auth.uid() IN (finder_id, claimant_id));

-- Quem propõe precisa ser participante, e o finder precisa ser o autor da publicação
DROP POLICY IF EXISTS "return_meetups_insert_participants" ON public.return_meetups;
CREATE POLICY "return_meetups_insert_participants"
  ON public.return_meetups FOR INSERT
  TO authenticated
  WITH CHECK (
    proposed_by = auth.uid()
    AND auth.uid() IN (finder_id, claimant_id)
    AND EXISTS (
      SELECT 1 FROM public.items i
      -- items.owner_id é text no banco; compara como texto
      WHERE i.id = item_id AND i.owner_id::text = finder_id::text
    )
  );

-- Ambos podem responder, cancelar ou substituir a proposta
DROP POLICY IF EXISTS "return_meetups_update_participants" ON public.return_meetups;
CREATE POLICY "return_meetups_update_participants"
  ON public.return_meetups FOR UPDATE
  TO authenticated
  USING (auth.uid() IN (finder_id, claimant_id))
  WITH CHECK (auth.uid() IN (finder_id, claimant_id));

GRANT SELECT, INSERT, UPDATE ON public.return_meetups TO authenticated;
